"""Phase 3 analysis exactly as pre-registered (docs/v3/preregistration_v3_phase3.md), plus Addendum A (post-hoc).

    .venv/bin/python scripts/v3/analyse_phase3.py --out docs/v3/phase3_results.md
"""
from __future__ import annotations

import argparse
import glob
import json
import os
import sys

import numpy as np
from scipy import stats

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
from run_phase3 import GRIDS, HORIZON, OUT, curve, episodes_to, run_name  # noqa: E402


def table(grid: str) -> dict:
    """{(K, arm): [(seed, episodes_to_90, censored, final_success, steps_run)]}"""
    g = GRIDS[grid]
    out = {}
    for alg in g["algs"]:
        for K in g["Ks"]:
            tmax = g["t_max"][K] if isinstance(g["t_max"], dict) else g["t_max"]
            for arm in g["arms"]:
                rows = []
                for s in g["seeds"]:
                    d = os.path.join(OUT, grid, run_name(alg, K, arm, s))
                    c = curve(d)
                    if c is None:
                        continue
                    e = episodes_to(d, 0.9, tmax)
                    censored = not np.any(c[1] >= 0.9)
                    rows.append((s, e, censored, float(c[1][-1]), int(c[0][-1])))
                out[(K, arm)] = rows
    return out


def ratio_stats(t: dict, K: int, num: str, den: str):
    a = {s: e for s, e, *_ in t.get((K, num), [])}
    b = {s: e for s, e, *_ in t.get((K, den), [])}
    seeds = sorted(set(a) & set(b))
    if not seeds:
        return None
    logr = np.log([a[s] / b[s] for s in seeds])
    ratio_of_means = float(np.mean([a[s] for s in seeds]) / np.mean([b[s] for s in seeds]))
    return {"seeds": seeds, "ratio_of_means": ratio_of_means, "mean_log_ratio": float(logr.mean()),
            "per_seed": dict(zip(seeds, np.exp(logr).round(3).tolist())), "logr": logr}


def report(grid: str, label: str) -> list[str]:
    t = table(grid)
    Ks = GRIDS[grid]["Ks"]
    L = [f"## {label} (`{grid}`)", "", "Episodes to 90% greedy test success (mean over seeds; censored runs at budget, count shown).", "",
         "| K | arm | n | episodes to 90% (mean) | censored | final success (mean) |", "|---|---|---|---|---|---|"]
    for K in Ks:
        for arm in GRIDS[grid]["arms"]:
            rows = t.get((K, arm), [])
            if not rows:
                continue
            L.append(f"| {K} | {arm} | {len(rows)} | {np.mean([r[1] for r in rows]):.0f} | {sum(r[2] for r in rows)} | "
                     f"{np.mean([r[3] for r in rows]):.3f} |")
    L += ["", "| K | difference / team (ratio of means) | per seed | team_vector / team |", "|---|---|---|---|"]
    logs = []
    for K in Ks:
        r = ratio_stats(t, K, "difference", "team")
        v = ratio_stats(t, K, "team_vector", "team")
        if r:
            logs.append((K, r["mean_log_ratio"]))
            L.append(f"| {K} | {r['ratio_of_means']:.3f} | {r['per_seed']} | {v['ratio_of_means']:.3f} |" if v else
                     f"| {K} | {r['ratio_of_means']:.3f} | {r['per_seed']} | - |")
    L.append("")
    # H3.1
    r1 = ratio_stats(t, min(Ks), "difference", "team")
    if r1:
        ok = 0.8 <= r1["ratio_of_means"] <= 1.25
        L.append(f"- **H3.1** (K = {min(Ks)}, ratio in [0.8, 1.25]): ratio {r1['ratio_of_means']:.3f} -> "
                 f"**{'SUPPORTED' if ok else 'NOT SUPPORTED'}**")
    # H3.2
    r8 = ratio_stats(t, max(Ks), "difference", "team")
    if r8 and len(r8["logr"]) > 1:
        x = r8["logr"]
        p = float(stats.ttest_1samp(x, np.log(0.67), alternative="less").pvalue) if np.std(x, ddof=1) > 0 else (
            0.0 if x.mean() < np.log(0.67) else 1.0)
        L.append(f"- **H3.2** (K = {max(Ks)}, paired one-sided t-test of log ratio < log 0.67): mean ratio "
                 f"{np.exp(x.mean()):.3f}, p = {p:.4f} -> **{'SUPPORTED' if p < 0.05 else 'NOT SUPPORTED'}**")
    # H3.3
    vs = [ratio_stats(t, K, "team_vector", "team") for K in Ks]
    vs = [(K, v["ratio_of_means"]) for K, v in zip(Ks, vs) if v]
    if vs:
        ok = all(0.8 <= v <= 1.25 for _, v in vs)
        L.append(f"- **H3.3** (team_vector / team in [0.8, 1.25] at every K): {[(K, round(v, 3)) for K, v in vs]} -> "
                 f"**{'SUPPORTED' if ok else 'NOT SUPPORTED'}** (descriptive)")
    # H3.4
    if len(logs) >= 3:
        rho = stats.spearmanr([k for k, _ in logs], [l for _, l in logs]).statistic
        L.append(f"- **H3.4** (mean log ratio decreases with K): Spearman rho = {rho:.2f} (descriptive)")
    return L + [""]


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--out", default=os.path.join(ROOT, "docs", "v3", "phase3_results.md"))
    a = p.parse_args()
    L = ["# Phase 3 results: the headroom gate", "",
         "Generated by `scripts/v3/analyse_phase3.py`. Pre-registration: `docs/v3/preregistration_v3_phase3.md`.", ""]
    L += report("gate", "Pre-registered gate (shared parameters, test every 10k steps)")
    for grid, label in (("gate_fine", "Addendum A1 (POST-HOC): test every 2k steps"),
                        ("gate_ns", "Addendum A2 (POST-HOC): no parameter sharing, test every 2k steps")):
        if glob.glob(os.path.join(OUT, grid, "*", "run_info.json")):
            L += report(grid, label)
    open(a.out, "w").write("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
