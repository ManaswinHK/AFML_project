"""Descriptive (not hypothesis-tested) v3 results -> docs/v3/descriptive_results.md.

Sections: semantic gap of a perfect one-step critic; data scaling; no-op vs removal null; coalition level;
order-4 coalition (Phase 2.4); control V1 (coverage); size transfer; V2 post-hoc read-outs.
Means over seeds with [min, max]. Seeds 5-9 unless a section says otherwise.

    .venv/bin/python scripts/v3/descriptive.py
"""
from __future__ import annotations

import glob
import json
import os
import sys
from collections import defaultdict

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
from aggregate import cell_condition  # noqa: E402
from analyse_prereg import metric  # noqa: E402


def load(grid):
    return [json.load(open(p)) for p in sorted(glob.glob(os.path.join(ROOT, "results", "v3", grid, "*.json")))]


def fmt(v):
    v = [x for x in v if x is not None]
    if not v:
        return "–"
    return f"{np.mean(v):.3f}" + (f" [{min(v):.2f}, {max(v):.2f}]" if len(v) > 1 else "")


def grid_table(grid, algs, metric_name, title, cond_key=cell_condition):
    rows = defaultdict(lambda: defaultdict(list))
    for r in load(grid):
        c = cond_key(r["cell"])
        for a in algs:
            rec = r["algs"].get(a)
            if rec is not None:
                rows[c][a].append(metric(rec, metric_name))
    if not rows:
        return [f"### {title}", "", "_no data_", ""]
    L = [f"### {title}", "", "| condition | " + " | ".join(algs) + " |", "|---|" + "---|" * len(algs)]
    for c in sorted(rows):
        L.append(f"| {' '.join(map(str, c))} | " + " | ".join(fmt(rows[c][a]) for a in algs) + " |")
    return L + [""]


def semantic_gap():
    rows = defaultdict(lambda: defaultdict(list))
    for r in load("confirm_main"):
        c = cell_condition(r["cell"])
        for kind in ("noop", "baseline"):
            rows[c][kind].append(r["semantic_gap"][kind]["missed"])
            rows[c][kind + "_l1"].append(r["semantic_gap"][kind]["l1"])
    L = ["### Semantic gap: a *perfect* one-step critic vs removal credit (exact per-step truth, gamma = 0.99)", "",
         "| condition | missed enabler credit (noop one-step) | L1 | missed (COMA-style baseline) | L1 |", "|---|---|---|---|---|"]
    for c in sorted(rows):
        d = rows[c]
        L.append(f"| {' '.join(map(str, c))} | {fmt(d['noop'])} | {fmt(d['noop_l1'])} | {fmt(d['baseline'])} | {fmt(d['baseline_l1'])} |")
    return L + ["", "Persistent ablation credit misses nothing by construction (Identity 1): its exact version *is* the truth.", ""]


def size_transfer():
    p = os.path.join(ROOT, "results", "v3", "size_transfer_confirm.json")
    if not os.path.exists(p):
        return ["### Size transfer", "", "_no data_", ""]
    by = defaultdict(lambda: defaultdict(list))
    for r in json.load(open(p)):
        k = f"b{r['b_train']}->b{r['b_test']}"
        for src in ("transfer", "in_size"):
            for m in ("l1", "leakage", "top_k", "step_r"):
                by[k][f"{src}_{m}"].append(r[src].get(m))
        by[k]["uniform_l1"].append(r["uniform"]["l1"])
    L = ["### Zero-shot size transfer of the set critic (seeds 5-9)", "",
         "| train -> test | transfer L1 | leakage | top-k | step r | in-size L1 | equal split |", "|---|---|---|---|---|---|---|"]
    for k, d in by.items():
        L.append(f"| {k} | {fmt(d['transfer_l1'])} | {fmt(d['transfer_leakage'])} | {fmt(d['transfer_top_k'])} | "
                 f"{fmt(d['transfer_step_r'])} | {fmt(d['in_size_l1'])} | {fmt(d['uniform_l1'])} |")
    return L + [""]


def v1():
    key = lambda c: (c["n_train"], c["epsilon"])
    L = grid_table("v1_coverage", ("qmix", "coma"), "step_r",
                   "Control V1 (reduced): per-step fidelity of one-step critics vs data size and noise (d = 25, b = 2; seeds 5-7). Condition = (n_train, epsilon)",
                   cond_key=key)
    L += grid_table("v1_coverage", ("qmix", "coma", "uniform"), "loo_c", "Control V1: end-to-end L1 vs closed-loop removal credit", cond_key=key)
    return L


def main():
    L = ["# v3 descriptive results (not hypothesis-tested)", "", "Generated by `scripts/v3/descriptive.py`.", ""]
    L += semantic_gap()
    L += grid_table("confirm_main", ("atd_noint", "atd_n25", "atd_n50", "atd_n100", "atd", "atd_n400", "atd_n800"),
                    "loo_cn", "Data scaling, MLP critic (fixed roles): L1 vs exact truth by number of stops (atd = 200)")
    L += grid_table("confirm_main", ("atd_noint", "atd_n25", "atd_n50", "atd_n100", "atd", "atd_n400", "atd_n800"),
                    "step_r", "Data scaling, MLP critic: per-step r vs exact kappa")
    L += grid_table("confirm_perm", ("atd", "atd_n800", "atd_set_n25", "atd_set_n50", "atd_set_n100", "atd_set", "atd_n800_set"),
                    "loo_cn", "Data scaling, shuffled roles: MLP (200, 800) vs set critic (25-800 stops)")
    L += grid_table("confirm_main", ("atd", "atd_remove", "atd_set"), "loo_c",
                    "No-op vs removal null, main grid: L1 vs closed-loop REMOVAL truth")
    L += grid_table("confirm_h5", ("atd", "atd_remove", "atd_set", "atd_set_remove"), "loo_c",
                    "No-op vs removal null, overlap/partial: L1 vs closed-loop REMOVAL truth (no-op critics are graded on the wrong game here, by design)")
    L += grid_table("confirm_main", ("atd", "atd_set", "table3_mix", "ece3_mix", "qmix", "vdn"), "div_c",
                    "Coalition level, main grid: dividend error vs closed-loop removal game")
    L += grid_table("confirm_main", ("atd", "atd_set"), "div_cn",
                    "Coalition level, main grid: ATD dividend error vs its own (no-op) game")
    L += grid_table("confirm_h5", ("atd_set", "atd_set_remove", "table2_mix", "table3_mix", "ece2_mix", "ece3_mix"), "div_c",
                    "Coalition level, overlap/partial: dividend error vs closed-loop removal game")
    L += grid_table("confirm_perm", ("atd", "atd_set", "atd_set_noroles", "table3_mix", "ece3_mix"), "div_c",
                    "Coalition level, shuffled roles: dividend error vs closed-loop removal game")
    L += grid_table("double_k4", ("uniform", "atd", "atd_set", "atd_noint", "table3_mix", "ece3_mix"), "loo_cn",
                    "Order-4 coalition (Phase 2.4; NOT pre-registered): individual L1")
    L += grid_table("double_k4", ("atd", "atd_set", "table3_mix", "ece3_mix"), "div_c",
                    "Order-4 coalition: dividend error (the only true dividend is on all four; order-3 models cannot represent it)")
    L += v1()
    L += size_transfer()
    L += grid_table("v2_posthoc", ("uniform", "atd", "mappo_int", "mappo_int_masked", "mappo_int_kdisc", "mappo_int_struct",
                                   "qmix_int", "qmix_int_masked", "qmix_int_kdisc", "qmix_int_struct"), "loo_cn",
                    "V2 post-hoc read-outs (POST-HOC; seeds 5-7): L1 vs exact removal credit")
    out = os.path.join(ROOT, "docs", "v3", "descriptive_results.md")
    open(out, "w").write("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
