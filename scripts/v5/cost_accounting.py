"""Simulator cost of exact difference rewards (review point 3; promised in docs/v3/preregistration_v3_phase3.md).

The difference arm steps n shadow copies (one per agent, agent i at no-op) alongside the real environment, so each
environment step costs n + 1 simulator steps (n = 2K agents on K lanes). The pre-registration said this cost would be
reported "separately as (n + 1)x environment steps"; v3 did not report it. Here: episodes to 90% greedy test success
per arm, and the same counted in simulator episodes. The team, team_vector and expected arms use one simulator (the
expected arm's per-lane tables are a few dictionary updates per step).

    .venv/bin/python scripts/v5/cost_accounting.py > docs/v5/cost_accounting.md
"""
from __future__ import annotations

import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(ROOT, "scripts", "v3"))
from analyse_phase3 import table  # noqa: E402
from run_phase3 import GRIDS  # noqa: E402

COPIES = {"difference": lambda K: 2 * K + 1}


def geo(x):
    return float(np.exp(np.mean(np.log(x))))


def report(grid, label, arms):
    t = table(grid)
    L = [f"### {label} (`{grid}`)", "",
         "| K | arm | simulators per step | episodes to 90% (geo. mean) | simulator episodes (geo. mean) | "
         "ratio vs team, episodes | ratio vs team, simulator cost |", "|---|---|---|---|---|---|---|"]
    for K in GRIDS[grid]["Ks"]:
        team = {s: e for s, e, *_ in t.get((K, "team"), [])}
        for arm in arms:
            rows = {s: e for s, e, *_ in t.get((K, arm), [])}
            if not rows:
                continue
            c = COPIES.get(arm, lambda K: 1)(K)
            seeds = sorted(set(rows) & set(team))
            r_ep = geo([rows[s] / team[s] for s in seeds])
            L.append(f"| {K} | {arm} | {c} | {geo(list(rows.values())):,.0f} | {geo([c * v for v in rows.values()]):,.0f} | "
                     f"{r_ep:.3f} | **{c * r_ep:.2f}** |")
    return L + [""]


def main():
    L = ["# Simulator cost of exact difference rewards", "",
         "Generated by `scripts/v5/cost_accounting.py`. Ratios are geometric means of per-seed ratios (paired by seed); "
         "a cost ratio above 1 means the arm used **more** simulation than team reward to reach 90% test success. "
         "Censored runs count at their budget, as in the original analyses.", ""]
    L += report("gate", "v3 Phase 3 gate (shared parameters, test every 10k steps; pre-registered)", ("difference",))
    L += report("gate_fine", "v3 Addendum A1 (shared parameters, test every 2k steps; post-hoc)", ("difference",))
    L += report("gate_ns", "v3 Addendum A2 (no parameter sharing; post-hoc)", ("difference",))
    L += report("online_credit", "v4 Part C (no parameter sharing; pre-registered)", ("expected", "difference"))
    print("\n".join(L))


if __name__ == "__main__":
    main()
