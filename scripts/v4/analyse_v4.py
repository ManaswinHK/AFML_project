"""Confirmatory analysis of docs/v4/preregistration_v4.md (Parts A, B, C). Writes docs/v4/results.md."""
from __future__ import annotations

import glob
import json
import os
import sys
from collections import defaultdict

import numpy as np
from scipy import stats

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(ROOT, "scripts", "v3"))
import stats as S  # noqa: E402
from analyse_prereg import fmt_family  # noqa: E402


def part_a(lines):
    lines += ["## Part A: mixed-size set critic", ""]
    for design, l1_tau, gap, ids in (("interp", 0.10, 0.10, ("A1", "A2")), ("extrap", 0.25, 0.30, ("A3", "A4"))):
        p = os.path.join(ROOT, "results", "v4", f"size_mixed_confirm_{design}.json")
        if not os.path.exists(p):
            lines += [f"_{design}: no data_", ""]
            continue
        res = json.load(open(p))
        mixed, single, topk, insz, uni = (defaultdict(list) for _ in range(5))
        for r in res:
            for b, rows in r["results"].items():
                mixed[(design, b)].append(rows["mixed"]["l1"])
                single[(design, b)].append(rows["single"]["l1"])
                topk[(design, b)].append(rows["mixed"]["top_k"])
                insz[(design, b)].append(rows["in_size"]["l1"])
                uni[(design, b)].append(rows["uniform"]["l1"])
        lines += [f"### {ids[0]}: {design}: mixed L1 < {l1_tau}", "", fmt_family(S.threshold_family(dict(mixed), l1_tau)), ""]
        lines += [f"### {ids[1]}: {design}: single - mixed > {gap}", "", fmt_family(S.paired_family(dict(mixed), dict(single), gap)), ""]
        lines += [f"### A5 ({design}): mixed top-k > 0.9", "", fmt_family(S.threshold_family(dict(topk), 0.9, "above")), ""]
        lines += [f"References ({design}): in-size L1 " + ", ".join(f"{k[1]}: {np.mean(v):.3f}" for k, v in insz.items())
                  + "; equal split " + ", ".join(f"{k[1]}: {np.mean(v):.3f}" for k, v in uni.items()), ""]
    return lines


def main():
    lines = ["# v4 confirmatory results (generated by scripts/v4/analyse_v4.py)", "",
             "Pre-registration: `docs/v4/preregistration_v4.md`. Seeds 10-14.", ""]
    lines = part_a(lines)
    try:
        from analyse_v4_bc import part_b, part_c, part_d
        lines = part_b(lines)
        lines = part_c(lines)
        lines = part_d(lines)
    except ImportError:
        pass
    out = os.path.join(ROOT, "docs", "v4", "results.md")
    open(out, "w").write("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
