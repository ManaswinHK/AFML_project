"""Sensitivity check A (Step 9): Shapley vs leave-one-out as the credit target.

No training: this re-reads the truths and per-method scores already stored in the Mode P cell JSONs
(`truth.shapley`, `truth.loo`, and each method's `summary_shapley` / `summary_loo`).

  A1. How far apart are the two targets themselves (L1 between normalised shares)?
  A2. Does the ranking of methods change with the target (Kendall tau; best method)?
  A3. Does the H5b verdict (ECE-k_mix beats uniform credit on individual L1) change with the target?

    .venv/Scripts/python scripts/sensitivity_shapley_loo.py

Writes results/mode_p/sensitivity/shapley_loo.md.
"""

import collections
import glob
import json
import os
import sys

import numpy as np
from scipy.stats import kendalltau

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
sys.path.insert(0, os.path.join(ROOT, "scripts"))

from analyse_h3 import uniform_l1  # noqa: E402
from analyse_h5 import MAX_ORDER, paired_less, test_block  # noqa: E402

MODE_P = os.path.join(ROOT, "results", "mode_p")
GRIDS = ("main", "h3", "h5", "h5_ref")
OUT = os.path.join(MODE_P, "sensitivity")
EPS = 1e-9


def layout_of(cell):
    return cell.get("layout", "coalition")


def setting_of(cell):
    return "critical" if cell.get("enabler_start", 0) else "slack"


def shares(v):
    v = np.asarray(v, float)
    s = v.sum()
    return None if abs(s) < EPS else v / s


def load_cells():
    cells = []
    for g in GRIDS:
        for f in sorted(glob.glob(os.path.join(MODE_P, g, "*.json"))):
            with open(f) as fh:
                rec = json.load(fh)
            if "truth" in rec and "loo" in rec["truth"]:
                cells.append((g, rec))
    return cells


def a1_truth_gap(cells):
    """(layout, enabler, b) -> per-cell mean L1 between Shapley and LOO shares, pooled over delays and seeds."""
    gap = collections.defaultdict(list)
    skipped = collections.Counter()
    for _, rec in cells:
        c = rec["cell"]
        diffs = []
        for sh, lo in zip(rec["truth"]["shapley"], rec["truth"]["loo"]):
            a, b = shares(sh), shares(lo)
            if a is None or b is None:
                skipped[layout_of(c)] += 1
                continue
            diffs.append(float(np.abs(a - b).sum()))
        if diffs:
            gap[(layout_of(c), setting_of(c), c["n_bystanders"])].append(
                (float(np.mean(diffs)), float(np.mean(np.array(diffs) < 1e-6))))
    return gap, skipped


def a2_rankings(cells):
    """condition (layout, enabler, b, delay) -> {alg: ([l1 loo per seed], [l1 shapley per seed])}."""
    cond = collections.defaultdict(lambda: collections.defaultdict(lambda: ([], [])))
    for g, rec in cells:
        c = rec["cell"]
        key = (layout_of(c), setting_of(c), c["n_bystanders"], c["delay"])
        for alg, a in rec["algs"].items():
            if "summary_loo" in a and "summary_shapley" in a:
                lo, sh = a["summary_loo"]["l1"], a["summary_shapley"]["l1"]
                if lo is not None and sh is not None:
                    cond[key][alg][0].append(lo)
                    cond[key][alg][1].append(sh)
    return cond


def a3_h5b(cells):
    """(target, alg, layout, delay) -> {seed: individual L1}, with uniform under each target."""
    out = collections.defaultdict(dict)
    for g, rec in cells:
        if g != "h5":
            continue
        c = rec["cell"]
        lay, dl, s = layout_of(c), c["delay"], c["seed"]
        for tgt in ("shapley", "loo"):
            out[(tgt, "uniform", lay, dl)][s] = float(np.mean([uniform_l1(v) for v in rec["truth"][tgt]]))
            for alg, a in rec["algs"].items():
                if alg in ("ece2_mix", "ece3_mix"):
                    out[(tgt, alg, lay, dl)][s] = a[f"summary_{tgt}"]["l1"]
    return out


def main():
    cells = load_cells()
    n_by_grid = collections.Counter(g for g, _ in cells)
    out = ["# Sensitivity A: Shapley vs leave-one-out", "",
           "Generated by `scripts/sensitivity_shapley_loo.py`. Re-analysis of stored results, no new runs. "
           f"Cells read: {dict(n_by_grid)}.", ""]

    # A1
    gap, skipped = a1_truth_gap(cells)
    out += ["## A1. How far apart are the two targets?", "",
            "L1 between the normalised Shapley and leave-one-out shares of each test episode (0 = identical, 2 = disjoint), "
            "averaged over episodes, then over cells (all delays and seeds; the truth does not depend on the delay "
            "except through clipped payouts). `identical` = share of episodes where the two agree to 1e-6.", "",
            "| layout | enabler | bystanders | cells | mean L1 | episodes identical |", "|---|---|---|---|---|---|"]
    for key in sorted(gap):
        v = np.array(gap[key])
        out.append(f"| {key[0]} | {key[1]} | {key[2]} | {len(v)} | {v[:, 0].mean():.3f} | {v[:, 1].mean():.2f} |")
    if skipped:
        out += ["", f"Episodes skipped because a target sums to ~0: {dict(skipped)}."]
    out.append("")

    # A2
    cond = a2_rankings(cells)
    out += ["## A2. Do method rankings change with the target?", "",
            "For each condition (layout, enabler, b, d), methods are ranked by mean individual L1 against each target "
            "(seed means). `tau` = Kendall tau between the two rankings (1 = same order). `best` = lowest-L1 method "
            "under leave-one-out / Shapley.", "",
            "| layout | enabler | b | d | methods | tau | best (loo) | best (Shapley) | same best |",
            "|---|---|---|---|---|---|---|---|---|"]
    taus, same_best, n_cond = collections.defaultdict(list), collections.Counter(), collections.Counter()
    for key in sorted(cond):
        algs = sorted(cond[key])
        if len(algs) < 3:
            continue
        lo = np.array([np.mean(cond[key][a][0]) for a in algs])
        sh = np.array([np.mean(cond[key][a][1]) for a in algs])
        tau = kendalltau(lo, sh).statistic
        bl, bs = algs[int(np.argmin(lo))], algs[int(np.argmin(sh))]
        taus[key[0]].append(tau)
        n_cond[key[0]] += 1
        same_best[key[0]] += int(bl == bs)
        out.append(f"| {key[0]} | {key[1]} | {key[2]} | {key[3]} | {len(algs)} | {tau:.2f} | {bl} | {bs} | "
                   f"{'✓' if bl == bs else '✗'} |")
    out += ["", "| layout | conditions | mean tau | same best method |", "|---|---|---|---|"]
    for lay in sorted(taus):
        out.append(f"| {lay} | {n_cond[lay]} | {np.nanmean(taus[lay]):.2f} | {same_best[lay]}/{n_cond[lay]} |")
    out.append("")

    # A3
    ps = a3_h5b(cells)
    out += ["## A3. Does the H5b verdict change with the target?", "",
            "H5b as pre-registered grades individual L1 against Shapley shares. Here it is re-run against the "
            "leave-one-out target as well, with the matching uniform baseline. Same rule: one-sided paired t-test over "
            "seeds, Holm within the block, supported only if every eligible condition is significant.", ""]
    for tgt in ("shapley", "loo"):
        rows = []
        for k in (2, 3):
            for lay in ("coalition", "overlap", "partial"):
                if MAX_ORDER[lay] > k:
                    continue
                for dl in (0, 50):
                    rows.append((f"ece{k}_mix vs uniform, {lay} d={dl}", ps[(tgt, f"ece{k}_mix", lay, dl)],
                                 ps[(tgt, "uniform", lay, dl)]))
        test_block(f"H5b against the {'Shapley' if tgt == 'shapley' else 'leave-one-out'} target", rows, out)

    text = "\n".join(out) + "\n"
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "shapley_loo.md"), "w", encoding="utf-8") as fh:
        fh.write(text)
    sys.stdout.buffer.write(text.encode("utf-8"))


if __name__ == "__main__":
    main()
