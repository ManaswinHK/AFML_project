"""POST-HOC (not pre-registered): uniform-credit baseline (1/n to every agent) on the Mode P
main grid, scored against each method's matched ground truth on the same valid test episodes.

No training: this re-reads the stored truth vectors in results/mode_p/main.

    .venv/Scripts/python scripts/posthoc_uniform.py
"""

import collections
import glob
import json
import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
sys.path.insert(0, os.path.join(ROOT, "scripts"))

from analyse_h3 import uniform_l1  # noqa: E402
from whoearned.experiments import MATCHED_TARGET  # noqa: E402

MAIN = os.path.join(ROOT, "results", "mode_p", "main")
OUT = os.path.join(ROOT, "results", "mode_p", "main_posthoc_uniform")
ALGS = ("vdn", "qmix", "coma", "mappo")


def main():
    # (alg, d, b, setting) -> [(method l1, uniform l1)] per seed
    per_seed = collections.defaultdict(list)
    for f in sorted(glob.glob(os.path.join(MAIN, "d*.json"))):
        with open(f) as fh:
            d = json.load(fh)
        c = d["cell"]
        setting = "critical" if c["enabler_start"] else "slack"
        for alg in ALGS:
            eps = d["algs"][alg]["episodes"]
            truth = d["truth"][MATCHED_TARGET[alg]]
            valid = [e for e in eps if e["matched"]["valid"]]
            l1 = np.mean([e["matched"]["l1"] for e in valid])
            uni = np.mean([uniform_l1(truth[e["episode"]]) for e in valid])
            per_seed[(alg, c["delay"], c["n_bystanders"], setting)].append((l1, uni))

    out = ["# Uniform-credit baseline on the main grid (POST-HOC)", "",
           "Generated by `scripts/posthoc_uniform.py`. Uniform credit gives 1/n to every agent. It is scored",
           "against each method's matched target (leave-one-out for all four) on that method's valid test",
           "episodes. Means ± sd over 5 seeds of per-seed means over 30 test episodes.", "",
           "| alg | d | b | enabler | L1 | uniform L1 | method − uniform | seeds beating uniform |",
           "|---|---|---|---|---|---|---|---|"]
    beats = collections.Counter()
    conds = collections.Counter()
    by_b = collections.defaultdict(list)
    for key in sorted(per_seed, key=lambda k: (ALGS.index(k[0]), k[1], k[2], k[3])):
        alg, dl, b, setting = key
        l1 = np.array([r[0] for r in per_seed[key]])
        un = np.array([r[1] for r in per_seed[key]])
        conds[alg] += 1
        beats[alg] += int(l1.mean() < un.mean())
        by_b[(alg, b)].append(l1.mean() - un.mean())
        out.append(f"| {alg} | {dl} | {b} | {setting} | {l1.mean():.3f} ± {l1.std(ddof=1):.3f} | {un.mean():.3f} "
                   f"| {l1.mean() - un.mean():+.3f} | {int((l1 < un).sum())}/{len(l1)} |")

    out += ["", "## Conditions where the method's mean beats uniform", "",
            "| alg | conditions beaten | mean (method − uniform) at b = 0 / 2 / 4 |", "|---|---|---|"]
    for alg in ALGS:
        gaps = " / ".join(f"{np.mean(by_b[(alg, b)]):+.3f}" for b in (0, 2, 4))
        out.append(f"| {alg} | {beats[alg]}/{conds[alg]} | {gaps} |")

    text = "\n".join(out) + "\n"
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "uniform_posthoc.md"), "w", encoding="utf-8") as fh:
        fh.write(text)
    sys.stdout.buffer.write(text.encode("utf-8"))


if __name__ == "__main__":
    main()
