"""Sensitivity check B (Step 9): open-loop vs closed-loop removal as the ground truth.

The default truth replays the recorded full-team actions with agents removed (open loop). The
alternative re-runs the scripted team with those agents absent, so the others can react (closed loop,
`ground_truth_closed_loop`). For every main-grid cell this regenerates the 30 test episodes, computes
both truths, and re-scores the stored method credits against the closed-loop leave-one-out target.
No critic is retrained.

Re-scoring is validated first: scoring the stored credit shares against the *stored* open-loop target
must reproduce the stored per-episode metrics exactly.

    .venv/Scripts/python scripts/sensitivity_loop.py --workers 10
    .venv/Scripts/python scripts/sensitivity_loop.py --report-only

Writes results/mode_p/main_closed_loop/ (re-scored copies of the cell JSONs, same names, with the
closed-loop metrics in place of the open-loop ones) and results/mode_p/sensitivity/loop.md. The
copies can be fed to `scripts/analyse_hypotheses.py` to re-test the hypotheses.
"""

import argparse
import copy
import glob
import json
import os
import re
import sys
from concurrent.futures import ProcessPoolExecutor, as_completed

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
sys.path.insert(0, os.path.join(ROOT, "scripts"))

from run_mode_p import cells  # noqa: E402
from whoearned.experiments import _roles, summarise  # noqa: E402
from whoearned.metrics import evaluate_against  # noqa: E402
from whoearned.replay import ground_truth_closed_loop, planted_dividends  # noqa: E402

MAIN = os.path.join(ROOT, "results", "mode_p", "main")
OUT = os.path.join(ROOT, "results", "mode_p", "main_closed_loop")
REPORT_DIR = os.path.join(ROOT, "results", "mode_p", "sensitivity")
ALGS = ("vdn", "qmix", "coma", "mappo")


def _shares(v):
    v = np.asarray(v, float)
    s = v.sum()
    return None if abs(s) < 1e-9 else v / s


def _l1(a, b):
    a, b = _shares(a), _shares(b)
    return None if a is None or b is None else float(np.abs(a - b).sum())


def _rescore(shares, target, enablers, bystanders):
    if shares is None:
        return {"valid": False}
    return evaluate_against(np.asarray(shares, float), np.asarray(target, float), enablers, bystanders).as_dict()


def run_cell(cell) -> str:
    cfg = cell.config()
    planted = planted_dividends(cfg)
    enablers, bystanders = _roles(cfg)
    rec = json.load(open(os.path.join(MAIN, f"{cell.key}.json")))
    test_eps = cell.episodes("test")

    closed = [ground_truth_closed_loop(cfg, lambda i=i: cell.team("test", i)) for i in range(len(test_eps))]

    gap = []
    for i, (ep, gt) in enumerate(zip(test_eps, closed)):
        open_loo, open_sh = rec["truth"]["loo"][i], rec["truth"]["shapley"][i]
        gap.append({"episode": i,
                    "loo_l1": _l1(open_loo, gt.leave_one_out), "shapley_l1": _l1(open_sh, gt.shapley),
                    "full_team_same": bool(abs(gt.v[-1] - ep.total) < 1e-9),
                    "closed_matches_plan": bool(gt.matches(planted))})

    new = copy.deepcopy(rec)
    for alg in ALGS:
        eps = new["algs"][alg]["episodes"]
        for i, e in enumerate(eps):
            # validation: stored credit shares against the stored open-loop target reproduce the stored row
            again = _rescore(e["shares"], rec["truth"]["loo"][i], enablers, bystanders)
            for k in ("valid", "l1", "leakage", "missed"):
                a, b = again.get(k), e["matched"].get(k)
                if (a is None) != (b is None) or (a is not None and not np.isclose(a, b, atol=1e-9)):
                    raise RuntimeError(f"{cell.key} {alg} ep {i} {k}: re-scored {a} != stored {b}")
            e["matched_open_loop"] = e["matched"]
            e["matched"] = e["loo"] = _rescore(e["shares"], closed[i].leave_one_out, enablers, bystanders)
        new["algs"][alg]["summary"] = new["algs"][alg]["summary_loo"] = summarise(eps)
    new["truth"] = {"shapley": [g.shapley.tolist() for g in closed], "loo": [g.leave_one_out.tolist() for g in closed]}
    new["loop_gap"] = gap
    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, f"{cell.key}.json")
    with open(path, "w") as f:
        json.dump(new, f)
    return path


def _verdict_lines(path):
    if not os.path.exists(path):
        return []
    return [ln.strip() for ln in open(path, encoding="utf-8") if re.search(r"Verdict|→ \*\*", ln)]


def report():
    recs = [json.load(open(f)) for f in sorted(glob.glob(os.path.join(OUT, "d*.json")))]
    if not recs:
        raise SystemExit("run the cells first")
    out = ["# Sensitivity B: open-loop vs closed-loop removal", "",
           "Generated by `scripts/sensitivity_loop.py`. For each main-grid cell the 30 test episodes were "
           f"regenerated and a closed-loop truth computed ({len(recs)} cells). Method credit is the stored credit; only "
           "the target changes.", ""]

    # B1: how far apart are the truths
    rows = {}
    for r in recs:
        c = r["cell"]
        key = (c["n_bystanders"], "critical" if c["enabler_start"] else "slack", c["delay"])
        g = r["loop_gap"]
        rows.setdefault(key, []).append((
            np.mean([x["loo_l1"] for x in g if x["loo_l1"] is not None]),
            np.mean([x["shapley_l1"] for x in g if x["shapley_l1"] is not None]),
            np.mean([x["loo_l1"] is not None and x["loo_l1"] < 1e-6 for x in g]),
            np.mean([x["full_team_same"] for x in g])))
    out += ["## B1. How far apart are the truths?", "",
            "L1 between open-loop and closed-loop normalised shares per test episode (0 = identical, 2 = disjoint), "
            "mean over episodes then over the 5 seeds. `identical` = share of episodes where the leave-one-out shares "
            "agree to 1e-6. `full team` = share of episodes where the closed-loop full-team run reproduces the test "
            "episode's return (a check on the regeneration).", "",
            "| bystanders | enabler | delay | LOO L1 | Shapley L1 | LOO identical | full team |", "|---|---|---|---|---|---|---|"]
    for key in sorted(rows):
        v = np.array(rows[key])
        out.append(f"| {key[0]} | {key[1]} | {key[2]} | {v[:, 0].mean():.3f} | {v[:, 1].mean():.3f} | "
                   f"{v[:, 2].mean():.2f} | {v[:, 3].mean():.2f} |")
    allv = np.array([x for k in rows for x in rows[k]])
    out += ["", f"Overall: LOO L1 {allv[:, 0].mean():.3f}, Shapley L1 {allv[:, 1].mean():.3f}, "
                f"LOO identical in {allv[:, 2].mean():.0%} of episodes; the largest per-condition LOO L1 is "
                f"{max(np.mean([x[0] for x in rows[k]]) for k in rows):.3f}.", ""]

    # B2: does any verdict change
    import analyse_hypotheses  # noqa: E402

    analyse_hypotheses.main(OUT)
    opn = _verdict_lines(os.path.join(MAIN, "hypotheses.md"))
    cls = _verdict_lines(os.path.join(OUT, "hypotheses.md"))
    changed = [(a, b) for a, b in zip(opn, cls) if a != b] if len(opn) == len(cls) else None
    out += ["## B2. Do the Mode P verdicts change?", "",
            "The pre-registered tests that score method credit against the removal target were re-run on the "
            "re-scored cells (`scripts/analyse_hypotheses.py results/mode_p/main_closed_loop`): H1a, H2, H2′ and H5's "
            "end-to-end side. H0 and H1b need quantities this script does not compute (a closed-loop no-op null and "
            "regenerated per-step counterfactuals); `scripts/sensitivity_loop_h0_h1b.py` adds them to the same cells. "
            + ("They have been added, so the lines below include H0 and H1b under the closed-loop truth."
               if all(r.get("h0_h1b_closed_loop") for r in recs) else
               "Until it has run, `hypotheses.md` in the re-scored folder repeats their open-loop values."), ""]
    if changed is None:
        out += ["(the verdict lines of the two files do not line up; compare `hypotheses.md` in both folders by hand)"]
    elif not changed:
        out += [f"All {len(opn)} verdict lines are identical in the two files."]
    else:
        out += [f"{len(changed)} of {len(opn)} verdict lines differ:", ""]
        for a, b in changed:
            out += [f"- open loop: {a}", f"  closed loop: {b}"]
    out.append("")

    text = "\n".join(out) + "\n"
    os.makedirs(REPORT_DIR, exist_ok=True)
    with open(os.path.join(REPORT_DIR, "loop.md"), "w", encoding="utf-8") as f:
        f.write(text)
    sys.stdout.buffer.write(text.encode("utf-8"))


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--workers", type=int, default=max(1, (os.cpu_count() or 2) - 2))
    p.add_argument("--report-only", action="store_true")
    a = p.parse_args()
    if not a.report_only:
        todo = [c for c in cells("main") if not os.path.exists(os.path.join(OUT, f"{c.key}.json"))]
        print(f"{len(todo)} cells to re-score with {a.workers} workers", flush=True)
        with ProcessPoolExecutor(max_workers=a.workers) as pool:
            futs = {pool.submit(run_cell, c): c for c in todo}
            for i, fut in enumerate(as_completed(futs), 1):
                try:
                    fut.result()
                    print(f"[{i}/{len(todo)}] {futs[fut].key} done", flush=True)
                except Exception as e:
                    print(f"[{i}/{len(todo)}] {futs[fut].key} FAILED: {e!r}", flush=True)
    report()


if __name__ == "__main__":
    main()
