"""H3 analysis of the Mode P H3 grid (overlap and partial-synergy layouts).

Pre-registered H3 (problem statement v2): some method-configuration pair has individual credit
error in the best third but dividend error in the worst third; NA2Q's coalition recovery falls
with d. Falsified if individual and dividend errors are tightly correlated.

POST-HOC additions (not pre-registered):
- a uniform-credit baseline (1/n to every agent) scored against the same truth;
- a check that STAS's d=0 and d=25 results are identical (it only sees the episode return).

    .venv/Scripts/python scripts/analyse_h3.py
"""

import collections
import glob
import json
import os
import sys

import numpy as np
from scipy.stats import spearmanr

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))

from whoearned.experiments import MATCHED_TARGET  # noqa: E402

H3 = os.path.join(ROOT, "results", "mode_p", "h3")
COALITION = ("vdn", "qmix", "na2q")
ALGS = ("vdn", "qmix", "coma", "mappo", "na2q", "stas")


def uniform_l1(values) -> float:
    s = np.asarray(values, float)
    s = s / s.sum()
    return float(np.abs(s - 1 / len(s)).sum())


def load():
    cells = []
    for f in sorted(glob.glob(os.path.join(H3, "*.json"))):
        with open(f) as fh:
            cells.append(json.load(fh))
    return cells


def main():
    cells = load()
    per_seed = collections.defaultdict(list)  # (alg, layout, d) -> [(l1, uniform l1, coalition dict)]
    for d in cells:
        c = d["cell"]
        uni = {t: float(np.mean([uniform_l1(v) for v in d["truth"][t]])) for t in ("shapley", "loo")}
        for alg in ALGS:
            a = d["algs"][alg]
            per_seed[(alg, c["layout"], c["delay"])].append(
                (a["summary"]["l1"], uni[MATCHED_TARGET[alg]], a.get("summary_coalition")))

    out = ["# H3 analysis (`results/mode_p/h3`)", "",
           "Generated by `scripts/analyse_h3.py`. Means over 5 seeds of per-seed means over 30 test episodes.", ""]

    out += ["## Individual credit vs uniform credit (uniform rows are POST-HOC)", "",
            "| alg | target | layout | d | L1 | uniform L1 | seeds beating uniform |", "|---|---|---|---|---|---|---|"]
    for (alg, lay, dl), rows in sorted(per_seed.items(), key=lambda kv: (ALGS.index(kv[0][0]), kv[0][1:])):
        l1 = np.array([r[0] for r in rows])
        un = np.array([r[1] for r in rows])
        out.append(f"| {alg} | {MATCHED_TARGET[alg]} | {lay} | {dl} | {l1.mean():.3f} ± {l1.std(ddof=1):.3f} "
                   f"| {un.mean():.3f} | {int((l1 < un).sum())}/{len(l1)} |")

    out += ["", "## Coalition level", "",
            "| alg | layout | d | dividend error | order ≤ 2 | recall | precision | interaction mass (true) |",
            "|---|---|---|---|---|---|---|---|"]
    pairs = []
    for (alg, lay, dl), rows in sorted(per_seed.items()):
        if alg not in COALITION:
            continue
        sc = {k: np.mean([r[2][k] for r in rows]) for k in
              ("dividend_error", "dividend_error_order2", "recall", "precision",
               "interaction_mass", "true_interaction_mass")}
        pairs.append((alg, lay, dl, np.mean([r[0] for r in rows]), sc["dividend_error"]))
        out.append(f"| {alg} | {lay} | {dl} | {sc['dividend_error']:.4f} | {sc['dividend_error_order2']:.4f} "
                   f"| {sc['recall']:.3f} | {sc['precision']:.3f} | {sc['interaction_mass']:.4f} "
                   f"({sc['true_interaction_mass']:.2f}) |")

    l1s = np.array([p[3] for p in pairs])
    des = np.array([p[4] for p in pairs])
    k = len(pairs) // 3
    best_l1 = set(np.argsort(l1s)[:k])
    worst_de = set(np.argsort(-des)[:k])
    rho = spearmanr(l1s, des)
    out += ["", "## Pre-registered H3 test", "",
            f"- Pairs (method × layout × d, coalition methods only): {len(pairs)}.",
            f"- Dividend error range: {des.min():.4f} to {des.max():.4f} "
            f"(spread {des.max() - des.min():.4f} on a 0–2 scale).",
            f"- Pairs with L1 in the best third and dividend error in the worst third: "
            f"{len(best_l1 & worst_de)} of {k} "
            + ", ".join(f"{pairs[i][0]}/{pairs[i][1]}/d{pairs[i][2]}" for i in sorted(best_l1 & worst_de)) + ".",
            f"- Spearman(L1, dividend error) = {rho.statistic:.2f} (p = {rho.pvalue:.3f}), computed over that spread.",
            "", "NA²Q coalition recovery by delay (recall / precision / interaction mass):", ""]
    for dl in (0, 25, 50):
        rs = [r[2] for lay in ("overlap", "partial") for r in per_seed[("na2q", lay, dl)]]
        out.append(f"- d = {dl}: {np.mean([r['recall'] for r in rs]):.3f} / "
                   f"{np.mean([r['precision'] for r in rs]):.3f} / {np.mean([r['interaction_mass'] for r in rs]):.4f}")

    out += ["", "## STAS delay invariance (POST-HOC)", ""]
    for lay in ("overlap", "partial"):
        diffs = []
        for d0 in (c for c in cells if c["cell"]["layout"] == lay and c["cell"]["delay"] == 0):
            s = d0["cell"]["seed"]
            d25 = next(c for c in cells if c["cell"]["layout"] == lay and c["cell"]["delay"] == 25
                       and c["cell"]["seed"] == s)
            e0, e25 = d0["algs"]["stas"]["episodes"], d25["algs"]["stas"]["episodes"]
            diffs += [abs(x["shapley"]["l1"] - y["shapley"]["l1"]) for x, y in zip(e0, e25)]
        out.append(f"- {lay}: max |per-episode L1(d=0) − L1(d=25)| = {max(diffs):.2e} over {len(diffs)} episodes.")

    text = "\n".join(out) + "\n"
    with open(os.path.join(H3, "h3_analysis.md"), "w", encoding="utf-8") as fh:
        fh.write(text)
    sys.stdout.buffer.write(text.encode("utf-8"))


if __name__ == "__main__":
    main()
