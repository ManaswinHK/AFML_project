"""H4 (Mode T): is return a weak proxy for credit faithfulness?  DESCRIPTIVE, not confirmatory.

    .venv/Scripts/python scripts/analyse_h4.py

Reads results/mode_t/*.json (one per run, from `run_mode_t.py eval`) and writes
results/mode_t/h4_analysis.md.

H4 (problem statement v2): within each method, return and 1 - L1 are weakly correlated, and at least two
methods with statistically indistinguishable return differ significantly in L1. Falsified if return
strongly predicts 1 - L1 within methods.

The statement gives no thresholds. These were fixed BEFORE any Mode T checkpoint was scored and are our
own choices, not pre-registered ones:
- correlation is "strong" if the cluster-bootstrap 95% CI of Spearman rho(return, 1 - L1) lies above 0.7,
  and "weak" if the point estimate is below 0.3;
- "statistically indistinguishable return" means a two-sided paired t-test over runs with p > 0.05
  (with few runs this is weak evidence of equivalence, and is stated as such);
- "differ significantly in L1" means a two-sided paired t-test over runs with p < 0.05.

Unit of analysis: a checkpoint. Return is the mean return of the 30 test episodes the credit is scored on
(epsilon = 0.2 behaviour). L1 is the end-to-end credit error against leave-one-out on the episodes where
credit is defined (the true values sum to a non-zero total). Checkpoints
with no test episode of defined credit have no L1 and are excluded; their number is reported. Checkpoints within
a run are dependent, so confidence intervals resample whole runs (delay x seed).
"""

import collections
import glob
import itertools
import json
import os
import sys
import zlib

import numpy as np
from scipy.stats import spearmanr, ttest_rel, wilcoxon

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODE_T = os.path.join(ROOT, "results", "mode_t")
N_BOOT = 4000
MIN_RUNS = 4  # a run-resampling CI from fewer runs is degenerate; such rows get no reading
MIN_VALID = 10  # sensitivity: keep only checkpoints where at least this many of the 30 episodes have defined credit


def load_runs():
    runs = []
    for f in sorted(glob.glob(os.path.join(MODE_T, "*_d*_s*.json"))):
        with open(f) as fh:
            runs.append(json.load(fh))
    return runs


def checkpoint_rows(run, min_valid=1):
    """(return, 1 - L1) for each checkpoint of a run with enough valid episodes; plus a count of the dropped."""
    rows, dropped = [], 0
    for c in run["checkpoints"]:
        s = c["summary"]
        if s["l1"] is None or s["n_valid"] < min_valid:
            dropped += 1
            continue
        rows.append((c["t_env"], c["return_mean"], 1.0 - s["l1"]))
    return rows, dropped


def rho(x, y):
    x, y = np.asarray(x, float), np.asarray(y, float)
    if len(x) < 4 or np.ptp(x) == 0 or np.ptp(y) == 0:
        return float("nan")
    return float(spearmanr(x, y).statistic)


def pooled_rho(runs_rows):
    x = [r for rows in runs_rows for _, r, _ in rows]
    y = [f for rows in runs_rows for _, _, f in rows]
    return rho(x, y)


def boot_ci(runs_rows, key):
    """Cluster-bootstrap 95% CI. The generator is seeded from ``key`` (method, delay, filter), so a CI does not
    change when other methods are added to the results folder."""
    rng = np.random.default_rng(zlib.crc32(key.encode()))
    stats = []
    n = len(runs_rows)
    for _ in range(N_BOOT):
        idx = rng.integers(0, n, n)
        v = pooled_rho([runs_rows[i] for i in idx])
        if not np.isnan(v):
            stats.append(v)
    return (float(np.percentile(stats, 2.5)), float(np.percentile(stats, 97.5))) if stats else (float("nan"),) * 2


def uniform_l1(loo):
    """L1 between uniform shares (1/n each) and the normalised leave-one-out shares of one episode."""
    t = np.asarray(loo, float)
    t = t / np.abs(t).sum()
    return float(np.abs(1.0 / len(t) - t).sum())


def label(point, ci):
    if np.isnan(point):
        return "undefined"
    if ci[0] > 0.7:
        return "strong"
    if point < 0.3:
        return "weak"
    return "moderate"


def main():
    runs = load_runs()
    if not runs:
        raise SystemExit("no Mode T eval JSONs; run `run_mode_t.py eval` first")
    by_alg = collections.defaultdict(list)
    for r in runs:
        by_alg[r["alg"]].append(r)
    out = ["# H4 analysis (Mode T, DESCRIPTIVE)", "",
           "Generated by `scripts/analyse_h4.py`. Thresholds were fixed before scoring and are our own (see the script's "
           "docstring). Unit: a checkpoint; confidence intervals resample whole runs (delay × seed).", "",
           f"Runs: {len(runs)} ({', '.join(f'{a}: {len(v)}' for a, v in sorted(by_alg.items()))}); seeded replay buffer: "
           f"{sorted({r.get('seed_episodes', 0) for r in runs})} scripted episodes; behavioural-cloning episodes: "
           f"{sorted({(r.get('bc') or {}).get('episodes', 0) for r in runs})}.", ""]

    # ---- within-method correlation
    out += ["## Within-method: Spearman ρ(return, 1 − L1)", "",
            "| method | delays | runs with credit | checkpoints used | dropped (no credit) | ρ pooled | 95% CI (resample runs) | reading |",
            "|---|---|---|---|---|---|---|---|"]
    summary = {}
    for alg, rs in sorted(by_alg.items()):
        for dl in (None,) + tuple(sorted({r["delay"] for r in rs})):
            sel = [r for r in rs if dl is None or r["delay"] == dl]
            rows, dropped = zip(*[checkpoint_rows(r) for r in sel])
            rows = [x for x in rows if x]
            if not rows:
                continue
            p, ci = pooled_rho(rows), boot_ci(rows, f"{alg}/{dl}")
            reading = label(p, ci) if len(rows) >= MIN_RUNS else f"too few runs ({len(rows)})"
            out.append(f"| {alg} | {'all' if dl is None else dl} | {len(rows)} | {sum(len(x) for x in rows)} | "
                       f"{sum(dropped)} | {p:+.2f} | [{ci[0]:+.2f}, {ci[1]:+.2f}] | {reading} |")
            if dl is None:
                summary[alg] = (p, ci)
    out += [""]
    # sensitivity
    out += [f"Sensitivity: keeping only checkpoints with at least {MIN_VALID} of 30 episodes with defined credit.", "",
            "| method | checkpoints used | ρ pooled | 95% CI |", "|---|---|---|---|"]
    for alg, rs in sorted(by_alg.items()):
        rows = [x for x in (checkpoint_rows(r, MIN_VALID)[0] for r in rs) if x]
        if rows:
            p, ci = pooled_rho(rows), boot_ci(rows, f"{alg}/min{MIN_VALID}")
            out.append(f"| {alg} | {sum(len(x) for x in rows)} | {p:+.2f} | [{ci[0]:+.2f}, {ci[1]:+.2f}] |")
    out += [""]

    # ---- between-method: same return, different L1?
    algs = sorted(by_alg)
    out += ["## Between methods: similar return, different L1?", ""]

    def stage(run, kind):
        rows, _ = checkpoint_rows(run)
        if not rows:
            return None
        if kind == "final":
            return rows[-1][1], 1.0 - rows[-1][2]
        late = [(r, 1.0 - f) for t, r, f in rows if t >= 240_000]
        return (float(np.mean([x[0] for x in late])), float(np.mean([x[1] for x in late]))) if late else None

    if len(algs) >= 2:
        out += ["Paired over runs (delay × seed) for every pair of methods; two-sided paired t-test, no multiplicity "
                "correction (the pairs are exploratory; a hit is a candidate, not a finding).", "",
                "| pair | stage | pairs | return (1st) | return (2nd) | return diff p | L1 (1st) | L1 (2nd) | L1 diff p | "
                "return indistinguishable and L1 different |", "|---|---|---|---|---|---|---|---|---|---|"]
        for a, b in itertools.combinations(algs, 2):
            runs_a = {(r["delay"], r["seed"]): r for r in by_alg[a]}
            runs_b = {(r["delay"], r["seed"]): r for r in by_alg[b]}
            keys = sorted(set(runs_a) & set(runs_b))
            for kind, title in (("final", "final checkpoint"), ("late", "mean of checkpoints at t ≥ 240k")):
                pairs = [(stage(runs_a[k], kind), stage(runs_b[k], kind)) for k in keys]
                pairs = [(x, y) for x, y in pairs if x is not None and y is not None]
                if len(pairs) < 4:
                    out.append(f"| {a} vs {b} | {title} | {len(pairs)} | – | – | – | – | – | – | too few |")
                    continue
                ra, rb = np.array([p[0][0] for p in pairs]), np.array([p[1][0] for p in pairs])
                la, lb = np.array([p[0][1] for p in pairs]), np.array([p[1][1] for p in pairs])
                p_ret = ttest_rel(ra, rb).pvalue if np.ptp(ra - rb) > 0 else 1.0
                p_l1 = ttest_rel(la, lb).pvalue if np.ptp(la - lb) > 0 else 1.0
                hit = p_ret > 0.05 and p_l1 < 0.05
                out.append(f"| {a} vs {b} | {title} | {len(pairs)} | {ra.mean():.2f} | {rb.mean():.2f} | {p_ret:.3f} | "
                           f"{la.mean():.3f} | {lb.mean():.3f} | {p_l1:.3f} | {'yes' if hit else 'no'} |")
        out += [""]
    else:
        out += ["Only one method was trained, so this clause cannot be assessed.", ""]

    # ---- post-hoc: learned credit vs uniform (1/n), on the same valid episodes
    out += ["## Post-hoc: learned credit vs uniform credit", "",
            "Uniform credit gives each agent 1/n, scored against the same leave-one-out truth on the same episodes as "
            "the method. Not part of H4; it places the Mode T L1 values on the scale used in Mode P "
            "(`docs/main_results.md` §3.3). Per run, the last checkpoint with defined credit; exact Wilcoxon over runs.", "",
            "| method | runs | L1 (method) | L1 (uniform) | runs where method < uniform | Wilcoxon p | "
            "checkpoints where method < uniform |", "|---|---|---|---|---|---|---|"]
    for alg, rs in sorted(by_alg.items()):
        last, n_ck, n_win = [], 0, 0
        for r in rs:
            final = None
            for c in r["checkpoints"]:
                if c["summary"]["l1"] is None:
                    continue
                uni = [uniform_l1(e["loo"]) for e in c["episodes"] if e["matched"]["valid"]]
                pair = (c["summary"]["l1"], float(np.mean(uni)))
                n_ck, n_win = n_ck + 1, n_win + (pair[0] < pair[1])
                final = pair
            if final is not None:
                last.append(final)
        m, u = np.array([x[0] for x in last]), np.array([x[1] for x in last])
        p = wilcoxon(m, u).pvalue if len(last) >= 2 and np.ptp(m - u) > 0 else float("nan")
        out.append(f"| {alg} | {len(last)} | {m.mean():.3f} | {u.mean():.3f} | {int((m < u).sum())}/{len(last)} | "
                   f"{p:.3f} | {n_win}/{n_ck} |")
    out += [""]

    # ---- reading
    strong =[a for a, (p, ci) in summary.items() if label(p, ci) == "strong"]
    weak = [a for a, (p, ci) in summary.items() if label(p, ci) == "weak"]
    out += ["## Reading", "",
            f"- Return strongly predicts 1 − L1 (CI above 0.7) for: {', '.join(strong) or 'no method'}.",
            f"- Weakly (point estimate below 0.3) for: {', '.join(weak) or 'no method'}.",
            "- Only methods that earn reward at some checkpoint can be assessed: VDN and QMIX trained with a seeded replay "
            "buffer, COMA and MAPPO after behavioural-cloning pretraining (both non-standard protocols).",
            "- Descriptive only: few methods, a seeded (non-standard) training protocol and our own thresholds.", ""]
    text = "\n".join(out) + "\n"
    with open(os.path.join(MODE_T, "h4_analysis.md"), "w", encoding="utf-8") as f:
        f.write(text)
    sys.stdout.buffer.write(text.encode("utf-8"))


if __name__ == "__main__":
    main()
